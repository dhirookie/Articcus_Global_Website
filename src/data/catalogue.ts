export type Service = (typeof SERVICES)[number];
export type ServiceId = Service['id'];
export type GroupId = keyof typeof GROUPS;
export type Industry = (typeof INDUSTRIES)[number];
export type IndustryId = Industry['id'];
export const GROUP_IDS: readonly GroupId[] = ['start', 'build', 'run'];
export function isServiceId(value: unknown): value is ServiceId {
  return (
    typeof value === 'string' &&
    SERVICES.some((service) => service.id === value)
  );
}
export function isIndustryId(value: unknown): value is IndustryId {
  return (
    typeof value === 'string' &&
    INDUSTRIES.some((industry) => industry.id === value)
  );
}
export function getService(id: ServiceId): Service {
  const service = SERVICES.find((item) => item.id === id);
  if (!service) throw new Error(`Unknown service: ${id}`);
  return service;
}
